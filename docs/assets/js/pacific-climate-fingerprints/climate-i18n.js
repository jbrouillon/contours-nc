function interpolate(template, variables) {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => (
    variables[key] === undefined || variables[key] === null ? "" : String(variables[key])
  ));
}

export function initialLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  if (queryLanguage === "en" || queryLanguage === "fr") return queryLanguage;
  try {
    const savedLanguage = window.localStorage.getItem("pacific-climate-language");
    if (savedLanguage === "en" || savedLanguage === "fr") return savedLanguage;
  } catch {
    // Storage may be unavailable in privacy-restricted contexts.
  }
  return window.navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function persistLanguage(language) {
  try {
    window.localStorage.setItem("pacific-climate-language", language);
  } catch {
    // The language still changes for the current page when storage is unavailable.
  }
  const url = new URL(window.location.href);
  url.searchParams.set("lang", language);
  window.history.replaceState({}, "", url);
}

export function translate(language, key, variables = {}) {
  const template = COPY[language]?.[key] ?? COPY.en[key] ?? key;
  return interpolate(template, variables);
}

export function territoryName(language, code) {
  return TERRITORIES[code]?.[language] ?? TERRITORIES[code]?.en ?? code;
}

export function localizeEnsoPhase(language, phase) {
  return ENSO_PHASES[phase]?.[language] ?? phase;
}

export function localizedNumber(language, value, maximumFractionDigits = 1, minimumFractionDigits = 0) {
  if (!Number.isFinite(value)) return translate(language, "common.noData");
  return new Intl.NumberFormat(language === "fr" ? "fr-FR" : "en-GB", {
    minimumFractionDigits,
    maximumFractionDigits,
    useGrouping: false
  }).format(value);
}

export function localizedPopulation(language, value) {
  if (!Number.isFinite(value)) return translate(language, "common.noData");
  return new Intl.NumberFormat(language === "fr" ? "fr-FR" : "en-GB", {
    notation: "compact",
    maximumSignificantDigits: 3
  }).format(value);
}
